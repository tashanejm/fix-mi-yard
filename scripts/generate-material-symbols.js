#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

// Configuration
const PACKAGE_DIR = path.join(process.cwd(), 'node_modules', '@material-symbols', 'svg-400', 'rounded');
const OUTPUT_DIR = path.join(process.cwd(), 'src', 'app', 'common');
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'material-symbols.ts');
const CLASS_NAME = 'MaterialSymbols';

function makeConstName(base) {
  // Uppercase and replace non-alphanumeric with underscores
  let name = base.toUpperCase().replace(/[^A-Z0-9]/g, '_');
  if (/^[0-9]/.test(name)) name = '_' + name;
  return name;
}

function run() {
  if (!fs.existsSync(PACKAGE_DIR)) {
    console.error('Source directory not found:', PACKAGE_DIR);
    process.exit(1);
  }

  if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  const files = fs.readdirSync(PACKAGE_DIR).filter(f => f.endsWith('.svg'));
  if (!files.length) {
    console.error('No SVG files found in', PACKAGE_DIR);
    process.exit(1);
  }

  let parts = [];
  parts.push('// THIS FILE IS AUTO-GENERATED BY scripts/generate-material-symbols.js\n');
  parts.push('// Do not edit directly. Run `npm run generate:material-symbols` to regenerate.\n\n');
  parts.push(`export class ${CLASS_NAME} {\n`);

  for (const file of files.sort()) {
    const base = path.basename(file, '.svg');
    const constName = makeConstName(base);
    const filePath = path.join(PACKAGE_DIR, file);
    let content = fs.readFileSync(filePath, 'utf8');

    // Escape backticks and template sequences so it is safe inside a template literal
    content = content.replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

    // Normalize newlines to LF inside the generated file for consistency
    content = content.replace(/\r\n?/g, '\n');

    parts.push(`  static readonly ${constName}: string = ` + '`' + content + '`' + ';\n\n');
  }

  parts.push('}\n');

  fs.writeFileSync(OUTPUT_FILE, parts.join(''), 'utf8');
  console.log('Generated', OUTPUT_FILE, 'with', files.length, 'icons');
}

run();

